def update_vi_catalog():
    """Bổ sung bản dịch VI cho English msgids còn thiếu."""
    po = polib.pofile(str(VI_PO), encoding="utf-8")
    existing = {e.msgid for e in po}
    added = 0
    for msgid, msgstr in VI_TRANSLATIONS.items():
        if msgid not in existing:
            entry = polib.POEntry(msgid=msgid, msgstr=msgstr)
            po.append(entry)
            added += 1
    po.save(str(VI_PO))
    print(f"VI catalog: {added} entries added (total {len(po)})")
    return po


def create_en_catalog():
    """Tạo hoặc cập nhật catalog EN cho Vietnamese msgids."""
    EN_DIR.mkdir(parents=True, exist_ok=True)
    if EN_PO.exists():
        po = polib.pofile(str(EN_PO), encoding="utf-8")
    else:
        po = polib.POFile()
        po.metadata = {
            "Content-Type": "text/plain; charset=UTF-8",
            "Content-Transfer-Encoding": "8bit",
            "Language": "en",
        }
    existing = {e.msgid for e in po}
    added = 0
    for msgid, msgstr in EN_TRANSLATIONS.items():
        if msgid not in existing:
            entry = polib.POEntry(msgid=msgid, msgstr=msgstr)
            po.append(entry)
            added += 1
    po.save(str(EN_PO))
    print(f"EN catalog: {added} entries added (total {len(po)})")
    return po


def compile_mo(po_path):
    mo_path = str(po_path).replace(".po", ".mo")
    po = polib.pofile(str(po_path), encoding="utf-8")
    po.save_as_mofile(mo_path)
    print(f"Compiled: {mo_path}")


